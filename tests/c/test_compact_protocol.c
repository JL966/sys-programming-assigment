#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "compact_protocol.h"

static void test_dut_hello_matches_literal_vector(void)
{
    unsigned char frame[24] = {
        0xA5,0x5A,0x01,0x01,0x00,0x02,0x00,0x00,
        0x01,0x00,0x00,0x00,0x01,0x00,0x00,0x00,
        0x00,0x00,0x00,0x00,0x00,0x00,0xD4,0x52
    };
    const unsigned char expected[24] = {
        0xA5,0x5A,0x01,0x01,0x02,0x00,0x00,0x00,
        0x01,0x00,0x00,0x00,0x08,0x01,0x00,0x02,
        0xE1,0x01,0x00,0x01,0x00,0x01,0x90,0x84
    };
    assert(CompactProtocol_Handle(frame, 2) == 1);
    assert(memcmp(frame, expected, sizeof expected) == 0);
}

static void test_corrupt_crc_has_no_response_or_mutation(void)
{
    unsigned char frame[24] = {
        0xA5,0x5A,0x01,0x01,0x00,0x01,0x00,0x00,
        0x01,0x00,0x00,0x00,0x01,0x00,0x01,0x00,
        0x00,0x00,0x00,0x00,0x00,0x00,0x24,0xA2
    };
    unsigned char before[24];
    memcpy(before, frame, sizeof frame);
    assert(CompactProtocol_Handle(frame, 1) == 0);
    assert(memcmp(frame, before, sizeof frame) == 0);
}

int main(void)
{
    test_dut_hello_matches_literal_vector();
    test_corrupt_crc_has_no_response_or_mutation();
    puts("C compact protocol tests passed");
    return 0;
}
